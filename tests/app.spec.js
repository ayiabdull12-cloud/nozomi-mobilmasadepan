import { test, expect } from '@playwright/test';
test('Alur warung: barang, penjualan, keuangan, laporan, dan pengaturan tersimpan', async ({ page, request }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: /Usaha tertata/ })).toBeVisible();
  await page.getByRole('navigation').getByRole('button', { name: 'Barang & stok' }).click();
  await page.getByRole('button', { name: 'Tambah barang', exact: true }).first().click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Nama barang').fill('Kopi Uji'); await dialog.getByLabel('Kode barang').fill(`TEST-${Date.now()}`);
  await dialog.getByLabel('Harga modal').fill('3000'); await dialog.getByLabel('Harga jual').fill('5000'); await dialog.getByLabel('Stok awal').fill('10');
  await dialog.getByRole('button', { name: 'Simpan barang' }).click(); await expect(dialog).not.toBeVisible();
  await page.getByRole('navigation').getByRole('button', { name: 'Kasir & penjualan' }).click();
  await page.getByRole('button', { name: /Kopi Uji/ }).last().click();
  await page.getByRole('button', { name: 'Lanjut pembayaran' }).click();
  await dialog.getByRole('button', { name: 'Uang pas' }).click();
  await dialog.getByRole('button', { name: 'Selesaikan & catat penjualan' }).click();
  await expect(dialog.getByText('Lunas', { exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Tutup', exact: true }).click();
  await page.getByRole('navigation').getByRole('button', { name: 'Keuangan', exact: true }).click();
  await page.getByRole('button', { name: 'Catat keuangan' }).click();
  await dialog.getByLabel('Nominal').fill('1000'); await dialog.getByLabel('Keterangan').fill('Plastik belanja uji');
  await dialog.getByRole('button', { name: 'Simpan catatan' }).click();
  await expect(page.getByText('Plastik belanja uji', { exact: true })).toBeVisible();
  const expenseRow = page.getByRole('row').filter({ hasText: 'Plastik belanja uji' });
  await expenseRow.getByRole('button', { name: 'Ubah catatan' }).click();
  await dialog.getByLabel('Nominal').fill('1500');
  await dialog.getByRole('button', { name: 'Simpan catatan' }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('navigation').getByRole('button', { name: 'Laporan', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Laporan laba & rugi' })).toBeVisible();
  await expect(page.locator('.net-profit')).toContainText('Rp 500');
  const state = await (await request.get('/api/state')).json();
  expect(state.products.find(p => p.name === 'Kopi Uji').stock).toBe(9);
  expect(state.sales.some(s => s.items.some(i => i.name === 'Kopi Uji') && s.status === 'paid')).toBeTruthy();
  await page.getByRole('navigation').getByRole('button', { name: 'Pengaturan', exact: true }).click();
  await page.getByLabel('Nama warung', { exact: true }).fill('Warung Makmur Uji');
  await page.getByRole('button', { name: 'Simpan pengaturan' }).click();
  await expect(page.getByRole('status')).toContainText('Pengaturan warung disimpan');
  await page.reload(); await expect(page.getByRole('heading', { name: /Usaha tertata/ })).toBeVisible();
  await expect(page.getByText('Warung Makmur Uji', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
test('Ponsel: navigasi, pencarian barang, dan modal dapat dipakai tanpa overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 }); await page.goto('/');
  await expect(page.getByRole('heading', { name: /Usaha tertata/ })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.getByRole('button', { name: 'Buka menu' }).click();
  await page.getByRole('navigation').getByRole('button', { name: 'Barang & stok' }).click();
  await page.getByRole('textbox', { name: /Cari nama/ }).fill('Kopi Uji');
  await expect(page.getByRole('cell', { name: /Kopi Uji/ }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Tambah barang', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.keyboard.press('Escape'); await expect(page.getByRole('dialog')).not.toBeVisible();
});
test('QRIS manual menunggu konfirmasi dana dan API menolak stok berlebih', async ({ page, request }) => {
  await page.goto('/'); await page.getByRole('navigation').getByRole('button', { name: 'Kasir & penjualan' }).click();
  await page.getByRole('button', { name: /Kopi Uji/ }).last().click();
  await page.getByRole('button', { name: 'Lanjut pembayaran' }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: 'QRIS', exact: true }).click();
  await dialog.getByRole('button', { name: 'Selesaikan & catat penjualan' }).click();
  await expect(dialog.getByRole('heading', { name: 'Selesaikan pembayaran' })).toBeVisible();
  await dialog.getByRole('checkbox').check();
  await dialog.getByRole('button', { name: 'Selesaikan & catat penjualan' }).click();
  await expect(dialog.getByText('Lunas', { exact: true })).toBeVisible();
  const state = await (await request.get('/api/state')).json();
  const product = state.products.find(p => p.name === 'Kopi Uji');
  const response = await request.post('/api/sales', { data: { method: 'Transfer', items: [{ id: product.id, qty: product.stock + 1 }] } });
  expect(response.status()).toBe(400);
  const after = await (await request.get('/api/state')).json();
  expect(after.products.find(p => p.id === product.id).stock).toBe(product.stock);
  expect(after.ledger.length).toBe(state.ledger.length);
});
